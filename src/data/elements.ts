export interface Element {
  atomicNumber: number;
  symbol: string;
  name: string;
  atomicMass: number;
  category: ElementCategory;
  electronConfiguration: string;
  electronShells: number[];
  group: number | null;
  period: number;
  block: string;
  facts: string[];
  discoveredBy?: string;
  discoveryYear?: number;
  meltingPoint?: number;
  boilingPoint?: number;
  density?: number;
  naturalOccurrence?: string;
}

export type ElementCategory =
  | "alkali-metal"
  | "alkaline-earth"
  | "transition-metal"
  | "post-transition-metal"
  | "metalloid"
  | "nonmetal"
  | "halogen"
  | "noble-gas"
  | "lanthanide"
  | "actinide";

